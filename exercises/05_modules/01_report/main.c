/*
# Task 1 — Two modules

Программа из двух модулей, один из которых пользуется другим. Здесь же
видна разница между тремя видами имён: скрытыми внутри файла (`static`),
общими для всей программы (`extern`) и локальными.

Этот файл уже готов, менять его не нужно. Рядом с ним нужно создать
`counter.h`, `counter.c`, `report.h`, `report.c` и `Makefile`.

## Модуль counter

extern int counter_step;

int counter_next(void);
void counter_reset(void);

- Внутри модуля хранится текущее значение счётчика, изначально 0.
  Это `static`-переменная в `counter.c`: из других файлов она не видна,
  менять её можно только через функции модуля.
- `counter_step` — шаг счётчика, изначально 1. Это глобальная переменная:
  она определена в `counter.c`, а в `counter.h` только объявлена
  со словом `extern`, чтобы другие файлы могли её читать и менять.
- `counter_next` увеличивает значение на `counter_step` и возвращает его.
- `counter_reset` возвращает модуль в начальное состояние:
  значение 0, шаг 1.

## Модуль report

int report_line(char *buffer, size_t size, const char *text);

- Записывает в `buffer` строку вида `<номер>: <текст>`, где номер —
  очередное значение `counter_next()`.
- `size` — размер буфера. Писать через `snprintf`: за границу буфера
  выходить нельзя.
- Возвращает 1, если строка поместилась целиком, иначе 0.
- Номер берётся при каждом вызове, даже если строка не поместилась.
- `report.c` подключает `counter.h` и ничего не знает о том, как счётчик
  устроен внутри.

Оба заголовка должны быть защищены от повторного включения.

## Makefile

- Компилятор, флаги и список объектных файлов заданы переменными
  `CC`, `CFLAGS` и `OBJS`.
- Объектные файлы собираются одним шаблонным правилом `%.o: %.c`.
- `make` собирает программу `app`.
- `make clean` удаляет `app` и все `.o`.
- `clean` объявлена как `.PHONY`.

## Проверка

`make test 5 1` сначала собирает задачу твоим Makefile, затем запускает
тесты модулей. `make run 5 1` собирает и запускает `app`.
*/

#include <stdio.h>

#include "counter.h"
#include "report.h"

int main(void)
{
    char line[32];
    const char* tasks[] = { "write code", "run tests", "fix bugs" };

    counter_step = 10;

    for (size_t i = 0; i < 3; i++) {
        if (report_line(line, sizeof(line), tasks[i])) {
            printf("%s\n", line);
        }
    }
    return 0;
}
